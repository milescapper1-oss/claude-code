#!/usr/bin/env python3
"""
Generate a one-page org-chart HTML per account from data/contacts_research.json.

Run AFTER build.py:   python scripts/make_orgmap.py
Outputs: data/orgmaps/<account>.html  (open in a browser; print-friendly)

Layers are INFERRED from title seniority (Leadership -> Global/Functional ->
Site/Working) — real names/titles, but the vertical bands are a seniority proxy,
NOT confirmed reporting lines.
"""
import json, html
from pathlib import Path
from collections import defaultdict

DATA = Path(__file__).resolve().parent.parent / "data"
OUT = DATA / "orgmaps"; OUT.mkdir(exist_ok=True)
rows = json.load(open(DATA / "contacts_research.json", encoding="utf-8"))

LAYERS = ["1. Leadership", "2. Global / Functional", "3. Site / Working"]
TIER_CLASS = {1: "t1", 2: "t2", 3: "t3", 0: "t0"}

CSS = """
*{box-sizing:border-box} body{margin:0;font-family:-apple-system,Segoe UI,Roboto,Arial,sans-serif;
background:#f4f5f7;color:#1c2230;padding:28px}
h1{font-size:20px;margin:0 0 2px} .sub{color:#5b6472;font-size:12px;margin:0 0 20px}
.band{margin:0 0 14px;border-radius:10px;padding:12px 14px}
.band h2{font-size:12px;letter-spacing:.06em;text-transform:uppercase;margin:0 0 10px;color:#3a4250}
.band.b1{background:#fdf0e4;border:1px solid #f4b183} .band.b2{background:#fff8e6;border:1px solid #ffd966}
.band.b3{background:#eef6ea;border:1px solid #b7d9a8}
.grid{display:flex;flex-wrap:wrap;gap:8px}
.card{background:#fff;border:1px solid #dce0e6;border-radius:8px;padding:8px 10px;min-width:190px;max-width:250px;
box-shadow:0 1px 2px rgba(0,0,0,.04)}
.card .nm{font-weight:600;font-size:13px} .card .ti{font-size:11px;color:#4a5568;margin-top:2px;line-height:1.3}
.card .mt{font-size:10px;color:#0a7a55;margin-top:4px} .card .st{font-size:10px;color:#8a92a0;margin-top:3px}
.pill{display:inline-block;font-size:9px;padding:1px 6px;border-radius:9px;margin-top:5px;font-weight:600}
.t1{background:#c6efce;color:#1c6b2f} .t2{background:#dde9f7;color:#1d4e89}
.t3{background:#fff2cc;color:#8a6d1b} .t0{background:#eee;color:#777}
.foot{color:#8a92a0;font-size:10px;margin-top:18px;border-top:1px solid #dce0e6;padding-top:10px}
"""

def card(c):
    mt = f'<div class="mt">★ {html.escape(c["meet_at"])}</div>' if c.get("meet_at") else ""
    st = f'<div class="st">{html.escape(c.get("sr",""))}</div>' if c.get("sr") else ""
    pill = f'<span class="pill {TIER_CLASS[c["tier"]]}">T{c["tier"] or "—"}</span>'
    return (f'<div class="card"><div class="nm">{html.escape(c["name"])}</div>'
            f'<div class="ti">{html.escape(c.get("title",""))}</div>{st}{mt}{pill}</div>')

accounts = sorted({r["company"] for r in rows})
index = []
for acc in accounts:
    sub = [r for r in rows if r["company"] == acc]
    by_layer = defaultdict(list)
    for r in sub:
        by_layer[r["layer"]].append(r)
    dm = len([r for r in sub if r["level"] >= 4])
    speakers = len([r for r in sub if r.get("meet_at")])
    bands = ""
    for i, ly in enumerate(LAYERS, 1):
        people = sorted(by_layer.get(ly, []), key=lambda r: (-r["level"], r["sr"], r["name"]))
        if not people: continue
        cards = "".join(card(c) for c in people)
        bands += f'<div class="band b{i}"><h2>{html.escape(ly)} · {len(people)}</h2><div class="grid">{cards}</div></div>'
    page = (f'<!doctype html><html><head><meta charset="utf-8"><title>{html.escape(acc)} org map</title>'
            f'<style>{CSS}</style></head><body>'
            f'<h1>{html.escape(acc)} — Saunders valve-BD org map</h1>'
            f'<p class="sub">{len(sub)} contacts · {dm} decision-makers (Director+) · {speakers} where-to-meet. '
            f'Layers inferred from title seniority — not confirmed reporting lines.</p>{bands}'
            f'<p class="foot">Generated by scripts/make_orgmap.py from contacts_source.csv. '
            f'★ = confirmed/active at a target event. Tier = valve-BD influence (T1 primary / T2 influencer / T3 exec).</p>'
            f'</body></html>')
    fn = OUT / (acc.replace("/", "-") + ".html")
    fn.write_text(page, encoding="utf-8")
    index.append((acc, len(sub), dm, fn.name))

# small index page linking all accounts
links = "".join(f'<li><a href="{fn}">{html.escape(a)}</a> — {n} contacts, {d} decision-makers</li>'
                for a, n, d, fn in index)
(OUT / "index.html").write_text(
    f'<!doctype html><html><head><meta charset="utf-8"><title>Org maps</title>'
    f'<style>{CSS}</style></head><body><h1>Account org maps</h1><ul>{links}</ul></body></html>', encoding="utf-8")
print(f"wrote {len(accounts)} org maps + index to {OUT}")
